#!/usr/bin/env python3
"""Converts the Feather icon set (MIT, see LICENSE-feather.txt) from SVG to Android VectorDrawables (stroke-only, white; tint at runtime).
usage: svg2vector.py <icons_dir> <res_drawable_dir>
Handles path / circle / ellipse / line / polyline / polygon / rect, which is everything Feather uses."""
import os, re, sys, xml.etree.ElementTree as ET

src, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)

def f(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return s if s else "0"

def circle(cx, cy, r):
    return f"M{f(cx-r)},{f(cy)}a{f(r)},{f(r)} 0 1,1 {f(2*r)},0a{f(r)},{f(r)} 0 1,1 {f(-2*r)},0"

def ellipse(cx, cy, rx, ry):
    return f"M{f(cx-rx)},{f(cy)}a{f(rx)},{f(ry)} 0 1,1 {f(2*rx)},0a{f(rx)},{f(ry)} 0 1,1 {f(-2*rx)},0"

def rect(x, y, w, h, rx, ry):
    rx = min(rx or ry or 0, w / 2); ry = min(ry or rx or 0, h / 2)
    if not rx and not ry:
        return f"M{f(x)},{f(y)}h{f(w)}v{f(h)}h{f(-w)}z"
    return (f"M{f(x+rx)},{f(y)}h{f(w-2*rx)}a{f(rx)},{f(ry)} 0 0,1 {f(rx)},{f(ry)}v{f(h-2*ry)}a{f(rx)},{f(ry)} 0 0,1 {f(-rx)},{f(ry)}"
            f"h{f(-(w-2*rx))}a{f(rx)},{f(ry)} 0 0,1 {f(-rx)},{f(-ry)}v{f(-(h-2*ry))}a{f(rx)},{f(ry)} 0 0,1 {f(rx)},{f(-ry)}z")

def points(p, close):
    nums = [float(x) for x in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", p)]
    pts = list(zip(nums[0::2], nums[1::2]))
    d = "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts)
    return d + ("z" if close else "")

count = 0
for fn in sorted(os.listdir(src)):
    if not fn.endswith(".svg"):
        continue
    name = fn[:-4].replace("-", "_")
    root = ET.parse(os.path.join(src, fn)).getroot()
    paths = []
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        a = el.attrib
        g = lambda k, d=0.0: float(a.get(k, d))
        if tag == "path": paths.append(a["d"])
        elif tag == "circle": paths.append(circle(g("cx"), g("cy"), g("r")))
        elif tag == "ellipse": paths.append(ellipse(g("cx"), g("cy"), g("rx"), g("ry")))
        elif tag == "line": paths.append(f"M{f(g('x1'))},{f(g('y1'))}L{f(g('x2'))},{f(g('y2'))}")
        elif tag == "polyline": paths.append(points(a["points"], False))
        elif tag == "polygon": paths.append(points(a["points"], True))
        elif tag == "rect": paths.append(rect(g("x"), g("y"), g("width"), g("height"), g("rx"), g("ry")))
    if not paths:
        print("no shapes in", fn); continue
    body = "\n".join(
        f'    <path\n        android:pathData="{d}"\n        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />'
        for d in paths)
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Feather icon "%s" (MIT). Generated by tools/icons/svg2vector.py; tinted at runtime. -->\n'
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n%s\n</vector>\n') % (fn[:-4], body)
    open(os.path.join(out, f"ic_{name}.xml"), "w").write(xml)
    count += 1
print("converted", count, "icons")
